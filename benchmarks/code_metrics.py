#!/usr/bin/env python3
"""
Static Corpus & Structural Analysis of the Python, OCaml, and F# Notebook Editions:
Collects cell counts, code lines (SLOC), comment lines, and directive counts
across all notebooks to contextualize execution performance in Chapter 5.
"""
import json
import subprocess
from pathlib import Path

BENCH_DIR = Path(__file__).resolve().parent
REPO_ROOT = BENCH_DIR.parent
DATA_DIR = BENCH_DIR / "results"
DATA_DIR.mkdir(parents=True, exist_ok=True)


def analyze_edition(root: Path, lang: str) -> dict:
    notebooks = [
        p for p in sorted(root.rglob("*.ipynb"))
        if ".ipynb_checkpoints" not in p.parts and ".validation" not in p.parts
    ]
    total_nb = len(notebooks)
    total_code_cells = 0
    total_md_cells = 0
    total_sloc = 0
    total_Blank_or_comment = 0

    for nb_path in notebooks:
        nb = json.loads(nb_path.read_text(encoding="utf-8"))
        for cell in nb.get("cells", []):
            ctype = cell.get("cell_type")
            if ctype == "markdown":
                total_md_cells += 1
            elif ctype == "code":
                total_code_cells += 1
                lines = "".join(cell.get("source", [])).splitlines()
                for line in lines:
                    s = line.strip()
                    if not s:
                        total_Blank_or_comment += 1
                    elif lang == "python" and s.startswith("#"):
                        total_Blank_or_comment += 1
                    elif lang == "fsharp" and s.startswith("//") and not s.startswith("#"):
                        total_Blank_or_comment += 1
                    elif lang == "ocaml" and s.startswith("(*") and s.endswith("*)"):
                        total_Blank_or_comment += 1
                    else:
                        total_sloc += 1

    ext_files, ext_sloc = analyze_external_sources(root, lang)
    total = total_sloc + ext_sloc
    return {
        "notebooks": total_nb,
        "code_cells": total_code_cells,
        "markdown_cells": total_md_cells,
        "sloc": total_sloc,
        "avg_sloc_per_nb": round(total_sloc / total_nb, 1) if total_nb else 0.0,
        "avg_cells_per_nb": round(total_code_cells / total_nb, 1) if total_nb else 0.0,
        "external_source_files": ext_files,
        "external_sloc": ext_sloc,
        "total_sloc": total,
    }


# Source files outside the notebooks that the lecture code loads (helper
# libraries, lexer/parser specifications, scripts).  Test drivers, build and
# documentation tooling, and generated files are excluded.
SOURCE_SUFFIXES = {
    "python": {".py"},
    "ocaml": {".ml", ".mli", ".mll", ".mly"},
    "fsharp": {".fs", ".fsx", ".fsi", ".fsl", ".fsy"},
}
EXCLUDED_PARTS = {".ipynb_checkpoints", ".validation", "tools", "Tests", "Lecture-Notes", "bin", "obj"}
GENERATED_MARKERS = ("Generated by", "Do not edit", "auto-generated")


def is_comment(line: str, lang: str) -> bool:
    if lang == "python":
        return line.startswith("#")
    if lang == "fsharp":
        return line.startswith("//")
    return line.startswith("(*") and line.endswith("*)")


def analyze_external_sources(root: Path, lang: str) -> tuple[int, int]:
    files = 0
    sloc = 0
    # Only version-controlled files count; local build output is ignored.
    tracked = subprocess.run(
        ["git", "ls-files", "-z", "--", "."], cwd=root, capture_output=True, check=True
    ).stdout.decode("utf-8").split("\0")
    for path in sorted(root / name for name in tracked if name):
        if path.suffix not in SOURCE_SUFFIXES[lang] or not path.is_file():
            continue
        if EXCLUDED_PARTS.intersection(path.relative_to(root).parts):
            continue
        text = path.read_text(encoding="utf-8", errors="replace")
        if any(marker in text[:400] for marker in GENERATED_MARKERS):
            continue
        files += 1
        for line in text.splitlines():
            s = line.strip()
            if s and not is_comment(s, lang):
                sloc += 1
    return files, sloc


def main():
    stats = {
        "Python": analyze_edition(REPO_ROOT / "python", "python"),
        "OCaml": analyze_edition(REPO_ROOT / "ocaml", "ocaml"),
        "FSharp": analyze_edition(REPO_ROOT / "f#", "fsharp"),
    }
    out = DATA_DIR / "corpus_metrics.json"
    out.write_text(json.dumps(stats, indent=2))
    print(json.dumps(stats, indent=2))


if __name__ == "__main__":
    main()
