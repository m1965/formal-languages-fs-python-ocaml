"""Generate ../lib/html5.ml from Python's table html.entities.html5.

The OCaml standard library has no table of the named character references of HTML5,
so the notebook 04-Html2Text.ipynb loads this generated file instead.
Usage:  python3 gen_html5_entities.py > ../lib/html5.ml
"""
from html.entities import html5

def ocaml_string(s: str) -> str:
    out = []
    for c in s:
        if c in '"\\':
            out.append('\\' + c)
        elif ord(c) < 32 or ord(c) == 127:
            out.append(f'\\{ord(c):03d}')
        else:
            out.append(c)
    return '"' + ''.join(out) + '"'

print('(* Generated by ../tools/gen_html5_entities.py from Python\'s html.entities.html5. Do not edit. *)')
print('(* html5 maps the name of an entity, e.g. "uuml;" or "uuml", to the string it denotes. *)')
print('let html5 : (string, string) Hashtbl.t =')
print('  let table = Hashtbl.create 2400 in')
print('  List.iter (fun (k, v) -> Hashtbl.replace table k v)')
print('    [')
for k in sorted(html5):
    print(f'      ({ocaml_string(k)}, {ocaml_string(html5[k])});')
print('    ];')
print('  table')
