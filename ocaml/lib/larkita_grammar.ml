(* Larkita for OCaml, part 6: the grammar loader (load_grammar.py).

   A grammar file is parsed with a canonical LR(1) parser for the grammar of grammars (the "meta
   grammar"), which is itself generated by Larkita.  The parse tree is then transformed step by step,
   in the same order as in the Python version, so that the auxiliary rules and the anonymous terminals
   get the same names:

     1. the terminals are turned into regular expressions,
     2. the abstract syntax tree of every alternative is determined (heads, pass-through, aliases),
     3. string literals and regular expressions in rules become (anonymous) terminals,
     4. the EBNF operators are expanded into auxiliary rules, and
     5. the trees are flattened into BNF rules. *)

module Larkita_grammar = struct
  open Larkita_base
  open Larkita_lexer
  open Larkita_lr

  (* ---------- Trees ---------- *)

  (* The parse trees of grammar files.  The trees are changed in place, and some subtrees are shared,
     as in Python; uid plays the role of Python's id(). *)
  type gnode =
    | T of gtree
    | Tk of token
    | Sy of symbol
    | Pt of pattern
    | Sp of ast_spec

  and gtree = { mutable data : string; mutable children : gnode list; uid : int }

  let uid_counter = ref 0
  let mk (data : string) (children : gnode list) : gtree = incr uid_counter; { data; children; uid = !uid_counter }
  let mkt data children = T (mk data children)

  let rec node_equal (a : gnode) (b : gnode) : bool =
    match (a, b) with
    | T x, T y -> x == y || (x.data = y.data && List.equal node_equal x.children y.children)
    | Tk x, Tk y -> x.type_ = y.type_ && x.value = y.value
    | Sy x, Sy y -> symbol_equal x y
    | Pt x, Pt y -> pattern_equal x y
    | Sp x, Sp y -> x.spec_id = y.spec_id
    | _ -> false

  (* Depth-first iteration, bottom-up (Tree.iter_subtrees) *)
  let iter_subtrees (t : gtree) : gtree list =
    let processed = Hashtbl.create 64 in
    let order = ref [] in
    let queue = Queue.create () in
    Queue.add t queue;
    while not (Queue.is_empty queue) do
      let sub = Queue.pop queue in
      if not (Hashtbl.mem processed sub.uid) then begin
        Hashtbl.add processed sub.uid ();
        order := sub :: !order;
        List.iter
          (fun c -> match c with T c when not (Hashtbl.mem processed c.uid) -> Queue.add c queue | _ -> ())
          (List.rev sub.children)
      end
    done;
    !order

  (* Tree.iter_subtrees_topdown *)
  let iter_subtrees_topdown (t : gtree) : gtree list =
    let result = ref [] in
    let rec go n = match n with T t -> result := t :: !result; List.iter go t.children | _ -> () in
    go (T t);
    List.rev !result

  let find_data (t : gtree) (d : string) : gtree list = List.filter (fun s -> s.data = d) (iter_subtrees t)

  let rec scan_values (pred : gnode -> bool) (t : gtree) : gnode list =
    List.concat_map (fun c -> match c with T s -> scan_values pred s | v -> if pred v then [ v ] else []) t.children

  let expand_kids_by_data (t : gtree) (datas : string list) : bool =
    let changed = ref false in
    t.children <-
      List.concat_map
        (fun c -> match c with T s when List.mem s.data datas -> changed := true; s.children | c -> [ c ])
        t.children;
    !changed

  let rec copy_tree (t : gtree) : gtree = mk t.data (List.map copy_node t.children)
  and copy_node (n : gnode) : gnode = match n with T t -> T (copy_tree t) | v -> v

  (* Transformer_InPlace: the children of every subtree are transformed, bottom-up *)
  let transform_in_place (f : gtree -> gnode) (t : gtree) : gnode =
    List.iter
      (fun sub -> sub.children <- List.map (fun c -> match c with T s -> f s | v -> v) sub.children)
      (iter_subtrees t);
    f t

  (* Transformer (recursive, creates new results) *)
  let rec transform (f : string -> gnode list -> gnode) (n : gnode) : gnode =
    match n with T t -> f t.data (List.map (transform f) t.children) | v -> v

  let tok_value = function Tk t -> t.value | _ -> failwith "Larkita: token expected"
  let tree_of = function T t -> t | _ -> failwith "Larkita: tree expected"

  (* ---------- The grammar of grammars ---------- *)

  let re_flags = "imslux"

  let meta_terminals =
    [ ("_LPAR", {|\(|}); ("_RPAR", {|\)|}); ("_LBRA", {|\[|}); ("_RBRA", {|\]|});
      ("OP", "[+*]|[?](?![a-z_])"); ("_COLON", ":"); ("_COMMA", ","); ("_OR", {|\||}); ("_DOT", {|\.(?!\.)|});
      ("_DOTDOT", {|\.\.|}); ("TILDE", "~"); ("RULE_MODIFIERS", "(!|![?]?|[?]!?)(?=[_a-z])");
      ("RULE", "_?[a-z][_a-z0-9]*"); ("TERMINAL", "_?[A-Z][_A-Z0-9]*"); ("STRING", {|"(\\"|\\\\|[^"\n])*?"i?|});
      ("REGEXP", Printf.sprintf {|/(?!/)(\\/|\\\\|[^/])*?/[%s]*|} re_flags); ("_NL", {|(\r?\n)+\s*|});
      ("_NL_OR", {|(\r?\n)+\s*\||}); ("WS", {|[ \t]+|}); ("COMMENT", {|\s*//[^\n]*|\s*#[^\n]*|});
      ("BACKSLASH", {|\\[ ]*\n|}); ("_TO", "->"); ("_IGNORE", "%ignore"); ("_OVERRIDE", "%override");
      ("_DECLARE", "%declare"); ("_EXTEND", "%extend"); ("_IMPORT", "%import"); ("NUMBER", {|[+-]?\d+|}) ]

  (* The meta-grammar uses Lark's tree-shaping conventions: rules whose name starts with "?" are
     replaced by their child if they have only one, rules whose name starts with "_" are inlined into
     their parent, and terminals whose name starts with "_" are filtered out. *)
  let meta_rules =
    [ ("start", [ "_list" ]);
      ("_list", [ "_item"; "_list _item" ]);
      ("_item", [ "rule"; "term"; "ignore"; "ast_ignore"; "import"; "declare"; "override"; "extend"; "_NL" ]);
      ("rule", [ "rule_modifiers RULE priority _COLON expansions _NL" ]);
      ("rule_modifiers", [ "RULE_MODIFIERS"; "" ]);
      ("priority", [ "_DOT NUMBER"; "" ]);
      ("expansions", [ "_expansions" ]);
      ("_expansions", [ "alias"; "_expansions _OR alias"; "_expansions _NL_OR alias" ]);
      ("?alias", [ "expansion _TO nonterminal"; "expansion _TO STRING"; "expansion ignore_literals"; "expansion" ]);
      ("ignore_literals", [ "_IGNORE _literals" ]);
      ("_literals", [ "STRING"; "_literals _COMMA STRING" ]);
      ("expansion", [ "_expansion" ]);
      ("_expansion", [ ""; "_expansion expr" ]);
      ("?expr", [ "atom"; "atom OP"; "atom TILDE NUMBER"; "atom TILDE NUMBER _DOTDOT NUMBER" ]);
      ("?atom", [ "_LPAR expansions _RPAR"; "maybe"; "value" ]);
      ("value", [ "terminal"; "nonterminal"; "literal"; "range" ]);
      ("terminal", [ "TERMINAL" ]);
      ("nonterminal", [ "RULE" ]);
      ("?name", [ "RULE"; "TERMINAL" ]);
      ("?symbol", [ "terminal"; "nonterminal" ]);
      ("maybe", [ "_LBRA expansions _RBRA" ]);
      ("range", [ "STRING _DOTDOT STRING" ]);
      ("term", [ "TERMINAL _COLON expansions _NL"; "TERMINAL _DOT NUMBER _COLON expansions _NL" ]);
      ("override", [ "_OVERRIDE rule"; "_OVERRIDE term" ]);
      ("extend", [ "_EXTEND rule"; "_EXTEND term" ]);
      ("ignore", [ "_IGNORE expansions _NL"; "_IGNORE _ignore_list _NL" ]);
      ("_ignore_list", [ "expansion _COMMA expansion"; "_ignore_list _COMMA expansion" ]);
      ("ast_ignore", [ "_IGNORE _COLON _literals _NL" ]);
      ("declare", [ "_DECLARE _declare_args _NL" ]);
      ("import", [ "_IMPORT _import_list _NL" ]);
      ("_import_list", [ "import_item"; "_import_list _COMMA import_item" ]);
      ("import_item", [ "_import_path"; "_import_path _LPAR name_list _RPAR"; "_import_path _TO name" ]);
      ("_import_path", [ "import_lib"; "import_rel" ]);
      ("import_lib", [ "_import_args" ]);
      ("import_rel", [ "_DOT _import_args" ]);
      ("_import_args", [ "name"; "_import_args _DOT name" ]);
      ("name_list", [ "_name_list" ]);
      ("_name_list", [ "name"; "_name_list _COMMA name" ]);
      ("_declare_args", [ "symbol"; "_declare_args symbol" ]);
      ("literal", [ "REGEXP"; "STRING" ]) ]

  let symbol_from_strcase (s : string) : symbol =
    if is_upper s then terminal ~filter_out:(String.starts_with ~prefix:"_" s) s else nonterminal s

  type meta_parser = {
    m_table : parse_table;
    m_rules : rule array;
    m_callbacks : (gnode list -> gnode) array;
    m_lexer : basic_lexer;
    m_conf : lexer_conf;
  }

  let meta_parser : meta_parser Lazy.t =
    lazy
      (let rules_with_options =
         List.concat_map
           (fun (name, alternatives) ->
             let expand1 = String.starts_with ~prefix:"?" name in
             let name = if expand1 then String.sub name 1 (String.length name - 1) else name in
             List.mapi
               (fun i x ->
                 let symbols = List.map symbol_from_strcase (List.filter (( <> ) "") (String.split_on_char ' ' x)) in
                 ({ origin = name; expansion = symbols; order = i; priority = None; ast = None }, expand1))
               alternatives)
           meta_rules
       in
       let a = Larkita_lr.build (List.map fst rules_with_options) "start" in
       assert (List.for_all (fun c -> c.resolved) a.conflicts);
       let callback (rule, expand1) : gnode list -> gnode =
         let to_include =
           List.concat
             (List.mapi
                (fun i sym ->
                  if sym.is_term && sym.filter_out then []
                  else [ (i, (not sym.is_term) && String.starts_with ~prefix:"_" sym.name) ])
                rule.expansion)
         in
         fun children ->
           let children = Array.of_list children in
           let filtered =
             List.concat_map
               (fun (i, to_expand) -> if to_expand then (tree_of children.(i)).children else [ children.(i) ])
               to_include
           in
           match filtered with [ x ] when expand1 -> x | _ -> mkt rule.origin filtered
       in
       let callbacks = Array.of_list ((fun _ -> failwith "root") :: List.map callback rules_with_options) in
       let terminals = List.map (fun (name, value) -> terminal_def name (pattern_re value)) meta_terminals in
       let conf = lexer_conf terminals [ "WS"; "COMMENT"; "BACKSLASH" ] in
       { m_table = parse_table a; m_rules = a.rules; m_callbacks = callbacks; m_lexer = basic_lexer conf; m_conf = conf })

  let meta_parse (text : string) : gnode =
    let m = Lazy.force meta_parser in
    let st = lexer_state text in
    Larkita_lr.parse m.m_table m.m_rules m.m_callbacks (fun t -> Tk t)
      (fun state -> next_token m.m_lexer st (Some state))
      (format_expected m.m_conf.terminals_by_name)

  (* ---------- Error messages for grammar files ---------- *)

  let grammar_errors =
    [ ("Incorrect type of value", [ "a: 1\n" ]);
      ("Unclosed parenthesis", [ "a: (\n" ]);
      ("Unmatched closing parenthesis", [ "a: )\n"; "a: [)\n"; "a: (]\n" ]);
      ("Expecting rule or terminal definition (missing colon)", [ "a\n"; "A\n"; "a->\n"; "A->\n"; "a A\n" ]);
      ("Illegal name for rules or terminals", [ "Aa:\n" ]);
      ("Unexpected colon", [ "a::\n"; "a: b:\n"; "a: B:\n"; "a: \"a\":\n" ]);
      ("Misplaced operator", [ "a: b??"; "a: b(?)"; "a:+\n"; "a:?\n"; "a:*\n"; "a:|*\n" ]);
      ("Expecting option (\"|\") or a new rule or terminal definition", [ "a:a\n()\n" ]);
      ("Terminal names cannot contain dots", [ "A.B\n" ]);
      ( "Expecting rule or terminal definition",
        [ "\"a\"\n"; "a: A\n\"a\"\n"; "A: \"a\"\n\"a\"\n"; "%import common.A\n\"a\"\n"; "%ignore A\n\"a\"\n" ] );
      ("%import expects a name", [ "%import \"a\"\n"; "%import a.B, \"a\"\n"; "%import a.B,\n" ]);
      ("%ignore expects a value", [ "%ignore %import\n" ]);
      ( "The elements of a list after %ignore cannot contain \"|\" or \"->\"",
        [ "%ignore A, B | C\n"; "%ignore A, B -> c\n"; "%ignore A, B, C | D\n"; "%ignore A, B, C -> d\n" ] ) ]

  let grammar_errors_in_all_positions =
    List.map
      (fun (label, examples) ->
        (label, List.concat_map (fun example -> List.map (fun first -> first ^ example) [ ""; "A: \"a\"\n" ]) examples))
      grammar_errors

  let token_specific_errors =
    [ ("Incorrect type of value", [ "NUMBER" ]);
      ("Unmatched closing parenthesis", [ "_RPAR"; "_RBRA" ]);
      ("Unexpected colon", [ "_COLON" ]);
      ("Misplaced operator", [ "OP" ]);
      ("The elements of a list after %ignore cannot contain \"|\" or \"->\"", [ "_OR"; "_NL_OR"; "_TO" ]) ]

  let same_set a b = List.sort_uniq compare a = List.sort_uniq compare b

  (* UnexpectedInput.match_examples *)
  let match_examples (e : unexpected_input) (examples : (string * string list) list) : string option =
    let candidate = ref None in
    let exception Found of string in
    try
      List.iter
        (fun (label, example) ->
          List.iter
            (fun malformed ->
              match meta_parse malformed with
              | _ -> ()
              | exception Unexpected_input ut ->
                  if ut.state = e.state then begin
                    let skip =
                      match (e.kind, ut.kind) with
                      | Unexpected_token { token = t1; expected = x1 }, Unexpected_token { token = t2; expected = x2 } ->
                          if not (same_set x1 x2) then true
                          else if t1.type_ = t2.type_ && t1.value = t2.value then raise (Found label)
                          else false
                      | _ -> false
                    in
                    if (not skip) && !candidate = None then candidate := Some label
                  end)
            example)
        examples;
      !candidate
    with Found label -> Some label

  let translate_parser_exception (e : unexpected_input) (token : token) (expected : string list) : string option =
    let examples =
      List.filter
        (fun (label, _) ->
          match List.assoc_opt label token_specific_errors with
          | Some types -> List.mem token.type_ types
          | None -> true)
        grammar_errors_in_all_positions
    in
    match match_examples e examples with
    | Some error -> Some error
    | None -> if List.mem "STRING" expected then Some "Expecting a value" else None

  (* ---------- Literals ---------- *)

  let unicode_category (u : Uchar.t) = Uucp.Gc.general_category u

  let is_id_start_char u =
    Uchar.to_int u = Char.code '_'
    || match unicode_category u with `Lu | `Ll | `Lt | `Lm | `Lo | `Mn | `Mc | `Pc -> true | _ -> false

  let is_id_continue_char u =
    is_id_start_char u || match unicode_category u with `Nd | `Nl -> true | _ -> false

  (* the value of a Python string literal u'''w''' (ast.literal_eval) *)
  let python_unescape (w : string) : string =
    let us = Array.of_list (utf8_decode w) in
    let n = Array.length us in
    let b = Buffer.create n in
    let code i = Uchar.to_int us.(i) in
    let is_hex c = (c >= 48 && c <= 57) || (c >= 97 && c <= 102) || (c >= 65 && c <= 70) in
    let hex i k =
      if i + k > n then raise (Grammar_error ("Cannot decode the escape sequence in " ^ w));
      let v = ref 0 in
      for j = i to i + k - 1 do
        let c = code j in
        if not (is_hex c) then raise (Grammar_error ("Cannot decode the escape sequence in " ^ w));
        v := (!v * 16) + int_of_string ("0x" ^ String.make 1 (Char.chr c))
      done;
      !v
    in
    let add c = Buffer.add_utf_8_uchar b (Uchar.of_int c) in
    let i = ref 0 in
    while !i < n do
      let c = code !i in
      if c = Char.code '\\' && !i + 1 < n then begin
        let d = code (!i + 1) in
        i := !i + 2;
        match Char.unsafe_chr (if d < 128 then d else 0) with
        | '\\' -> add 92
        | '\'' -> add 39
        | '"' -> add 34
        | 'a' -> add 7
        | 'b' -> add 8
        | 'f' -> add 12
        | 'n' -> add 10
        | 'r' -> add 13
        | 't' -> add 9
        | 'v' -> add 11
        | '\n' -> ()
        | 'x' -> add (hex !i 2); i := !i + 2
        | 'u' -> add (hex !i 4); i := !i + 4
        | 'U' -> add (hex !i 8); i := !i + 8
        | '0' .. '7' ->
            let v = ref (d - 48) in
            let k = ref 0 in
            while !k < 2 && !i < n && code !i >= 48 && code !i <= 55 do
              v := (!v * 8) + (code !i - 48);
              incr i;
              incr k
            done;
            add !v
        | _ -> add 92; add d
      end
      else (add c; incr i)
    done;
    Buffer.contents b

  let eval_escaping (s : string) : string =
    let us = utf8_decode s in
    let w = Buffer.create (String.length s) in
    let rec go = function
      | [] -> ()
      | n :: rest ->
          Buffer.add_utf_8_uchar w n;
          if Uchar.to_int n = Char.code '\\' then begin
            match rest with
            | [] -> raise (Grammar_error (Printf.sprintf "Literal ended unexpectedly (bad escaping): `%s`" (py_repr s)))
            | n2 :: rest ->
                let c2 = Uchar.to_int n2 in
                if c2 = Char.code '\\' then Buffer.add_string w "\\\\"
                else if not (c2 < 128 && String.contains "Uuxnftr" (Char.chr c2)) then Buffer.add_char w '\\';
                Buffer.add_utf_8_uchar w n2;
                go rest
          end
          else go rest
    in
    go us;
    let replace_all sub by str =
      let sl = String.length sub in
      let b = Buffer.create (String.length str) in
      let i = ref 0 in
      while !i < String.length str do
        if !i + sl <= String.length str && String.sub str !i sl = sub then (Buffer.add_string b by; i := !i + sl)
        else (Buffer.add_char b str.[!i]; incr i)
      done;
      Buffer.contents b
    in
    let w = replace_all "\\\"" "\"" (Buffer.contents w) in
    let w = replace_all "'" "\\'" w in
    python_unescape w

  let replace_all sub by str =
    let sl = String.length sub in
    let b = Buffer.create (String.length str) in
    let i = ref 0 in
    while !i < String.length str do
      if !i + sl <= String.length str && String.sub str !i sl = sub then (Buffer.add_string b by; i := !i + sl)
      else (Buffer.add_char b str.[!i]; incr i)
    done;
    Buffer.contents b

  let literal_to_pattern (literal : token) : pattern =
    let v = literal.value in
    let rfind c = match String.rindex_opt v c with Some i -> i | None -> -1 in
    let flag_start = max (rfind '/') (rfind '"') + 1 in
    let flags = String.sub v flag_start (String.length v - flag_start) in
    if literal.type_ = "STRING" && String.contains v '\n' then raise (Grammar_error "You cannot put newlines in string literals");
    if literal.type_ = "REGEXP" && String.contains v '\n' && not (String.contains flags 'x') then
      raise (Grammar_error "You can only use newlines in regular expressions with the `x` (verbose) flag");
    let v = String.sub v 0 flag_start in
    let x = String.sub v 1 (String.length v - 2) in
    let s = eval_escaping x in
    if s = "" then raise (Grammar_error (Printf.sprintf "Empty terminals are not allowed (%s)" literal.value));
    if literal.type_ = "STRING" then pattern_str ~raw:literal.value ~flags (replace_all "\\\\" "\\" s)
    else pattern_re ~raw:literal.value ~flags s

  (* the text of a string literal token, e.g. ":=" for the token "\":=\"" *)
  let literal_text (literal : token) : string = (literal_to_pattern literal).value

  (* ---------- Terminals: trees to patterns ---------- *)

  (* PrepareLiterals *)
  let prepare_literals (t : gtree) : gnode =
    match (t.data, t.children) with
    | "literal", [ Tk l ] -> mkt "pattern" [ Pt (literal_to_pattern l) ]
    | "child_literal", [ Tk l ] -> mkt "child_pattern" [ Pt (literal_to_pattern l) ]
    | "range", [ Tk s; Tk e ] ->
        let inner v = String.sub v 1 (String.length v - 2) in
        if utf8_length (eval_escaping (inner s.value)) <> 1 || utf8_length (eval_escaping (inner e.value)) <> 1 then
          raise (Grammar_error "A range must consist of single characters");
        mkt "pattern" [ Pt (pattern_re (Printf.sprintf "[%s-%s]" (inner s.value) (inner e.value))) ]
    | _ -> T t

  (* TerminalTreeToPattern *)
  let rec terminal_tree_to_pattern (data : string) (children : gnode list) : gnode =
    let pat = function Pt p -> p | _ -> failwith "Larkita: pattern expected" in
    match data with
    | "pattern" -> List.hd children
    | "expansion" -> (
        match children with
        | [] -> Pt (pattern_str "")
        | [ p ] -> p
        | items -> Pt (pattern_re (String.concat "" (List.map (fun i -> to_regexp (pat i)) items))))
    | "expansions" -> (
        match children with
        | [ p ] -> p
        | exps ->
            let exps = List.map pat exps in
            let key p = (- max_width p, - min_width p, - utf8_length p.value) in
            let exps = List.stable_sort (fun a b -> compare (key a) (key b)) exps in
            Pt (pattern_re ("(?:" ^ String.concat "|" (List.map to_regexp exps) ^ ")")))
    | "expr" -> (
        let inner = pat (List.hd children) in
        let op = tok_value (List.nth children 1) in
        let op =
          if op = "~" then
            match List.map tok_value (drop 2 children) with
            | [ k ] -> Printf.sprintf "{%d}" (int_of_string k)
            | [ mn; mx ] ->
                let mn = int_of_string mn and mx = int_of_string mx in
                if mx < mn then
                  raise (Grammar_error (Printf.sprintf "Bad Range for %s (%d..%d isn't allowed)" (pattern_repr inner) mn mx));
                Printf.sprintf "{%d,%d}" mn mx
            | _ -> assert false
          else op
        in
        Pt (pattern_re ~flags:inner.flags (Printf.sprintf "(?:%s)%s" (to_regexp inner) op)))
    | "maybe" ->
        let q = { type_ = "OP"; value = "?"; start_pos = 0; line = 0; column = 0; end_line = 0; end_column = 0; end_pos = 0; byte_pos = 0 } in
        terminal_tree_to_pattern "expr" (children @ [ Tk q ])
    | "alias" -> raise (Grammar_error "Aliases (->) and %ignore annotations are not allowed in terminals")
    | "value" -> List.hd children
    | _ -> mkt data children

  (* ---------- The abstract syntax trees of the alternatives ---------- *)

  (* _make_ast_spec: the head consists of all string literals of the alternative that are not
     ignored, in textual order *)
  let make_ast_spec (rule_name : string) (expansion : gtree) (ignore : string list) (alias : string option) : ast_spec =
    let literals = ref [] in
    let symbols = ref 0 in
    let is_simple = ref true in
    let rec visit (node : gnode) =
      match node with
      | Sy _ -> incr symbols
      | T t -> (
          if t.data = "alias" then
            raise
              (Grammar_error
                 (Printf.sprintf
                    "In rule %s: an alias (->) or an %%ignore annotation can only be given at the end of an alternative"
                    rule_name));
          match (t.data, t.children) with
          | "literal", [ Tk token ] ->
              if token.type_ = "STRING" then begin
                let text = literal_text token in
                if not (List.mem text ignore) then literals := text :: !literals
              end
              else incr symbols
          | ("child_literal" | "range"), _ -> incr symbols
          | _ ->
              if t.data = "expr" || t.data = "maybe" || (t.data = "expansions" && List.length t.children > 1) then
                is_simple := false;
              List.iter (fun c -> match c with T _ | Sy _ -> visit c | _ -> ()) t.children)
      | _ -> ()
    in
    visit (T expansion);
    let literals = List.rev !literals in
    match alias with
    | Some a -> ast_spec (Some [ a ])
    | None ->
        if literals <> [] then ast_spec (Some literals)
        else if !symbols = 1 && !is_simple then ast_spec None
        else ast_spec (Some [ rule_name ])

  (* _expand_alternatives: the alternatives that the inner alternatives of tree abbreviate *)
  let rec expand_alternatives (t : gtree) : gtree list =
    match t.data with
    | "expansions" -> List.concat_map (fun c -> expand_alternatives (tree_of c)) t.children
    | "expansion" ->
        let variants =
          List.fold_left
            (fun variants child ->
              let options =
                match child with
                | T c when c.data = "expansion" || c.data = "expansions" -> List.map (fun v -> T v) (expand_alternatives c)
                | c -> [ c ]
              in
              List.concat_map (fun variant -> List.map (fun option -> variant @ [ option ]) options) variants)
            [ [] ] t.children
        in
        List.map (fun v -> mk "expansion" v) variants
    | _ -> [ t ]

  (* _mark_child_literals *)
  let rec mark_child_literals ?(inside = false) (t : gtree) (ignore : string list) : unit =
    List.iter
      (fun c ->
        match c with
        | T child ->
            if child.data = "literal" then begin
              match child.children with
              | [ Tk token ] when inside && token.type_ = "STRING" && not (List.mem (literal_text token) ignore) ->
                  child.data <- "child_literal"
              | _ -> ()
            end
            else
              mark_child_literals ~inside:(inside || (child.data = "expansions" && List.length child.children > 1)) child ignore
        | _ -> ())
      t.children

  (* _attach_ast_specs *)
  let attach_ast_specs (rule_name : string) (t : gtree) (ast_ignore : string list) : unit =
    assert (t.data = "expansions");
    while expand_kids_by_data t [ "expansions" ] do () done;
    let alternatives =
      List.concat_map
        (fun alternative ->
          let alternative = tree_of alternative in
          let expansion, alias, ignore =
            if alternative.data = "alias" then
              match alternative.children with
              | [ T expansion; T arg ] when arg.data = "ignore_literals" ->
                  (expansion, None, ast_ignore @ List.map (function Tk t -> literal_text t | _ -> assert false) arg.children)
              | [ T expansion; Tk arg ] -> (expansion, Some (literal_text arg), ast_ignore)
              | [ T expansion; Sy arg ] -> (expansion, Some arg.name, ast_ignore)
              | _ -> assert false
            else (alternative, None, ast_ignore)
          in
          let variants =
            match alias with
            | None -> List.map copy_tree (dedup ~eq:(fun a b -> node_equal (T a) (T b)) (expand_alternatives expansion))
            | Some _ -> [ expansion ]
          in
          List.map
            (fun variant ->
              mark_child_literals variant ignore;
              mkt "alias" [ T variant; Sp (make_ast_spec rule_name variant ignore alias) ])
            variants)
        t.children
    in
    t.children <- alternatives

  (* ---------- Anonymous terminals (PrepareAnonTerminals) ---------- *)

  let terminal_names =
    [ (".", "DOT"); (",", "COMMA"); (":", "COLON"); (";", "SEMICOLON"); ("+", "PLUS"); ("-", "MINUS"); ("*", "STAR");
      ("/", "SLASH"); ("\\", "BACKSLASH"); ("|", "VBAR"); ("?", "QMARK"); ("!", "BANG"); ("@", "AT"); ("#", "HASH");
      ("$", "DOLLAR"); ("%", "PERCENT"); ("^", "CIRCUMFLEX"); ("&", "AMPERSAND"); ("_", "UNDERSCORE");
      ("<", "LESSTHAN"); (">", "MORETHAN"); ("=", "EQUAL"); ("\"", "DBLQUOTE"); ("'", "QUOTE"); ("`", "BACKQUOTE");
      ("~", "TILDE"); ("(", "LPAR"); (")", "RPAR"); ("{", "LBRACE"); ("}", "RBRACE"); ("[", "LSQB"); ("]", "RSQB");
      ("\n", "NEWLINE"); ("\r\n", "CRLF"); ("\t", "TAB"); (" ", "SPACE") ]

  type anon = {
    mutable terminals : terminal_def list;          (* in the order of their definition *)
    term_set : (string, unit) Hashtbl.t;
    mutable term_reverse : (pattern * terminal_def) list;   (* the last definition of a pattern comes first *)
    mutable anon_i : int;
  }

  let make_anon (terminals : terminal_def list) : anon =
    let term_set = Hashtbl.create 32 in
    List.iter (fun (t : terminal_def) -> Hashtbl.replace term_set t.name ()) terminals;
    { terminals; term_set; term_reverse = List.rev_map (fun t -> (t.pattern, t)) terminals; anon_i = 0 }

  let terminal_name (an : anon) (p : pattern) : string =
    let find p : terminal_def option = List.find_map (fun (q, td) -> if pattern_equal p q then Some td else None) an.term_reverse in
    let term_name =
      if p.is_str then
        match find p with
        | Some td -> Some td.name
        | None ->
            let name =
              match List.assoc_opt p.value terminal_names with
              | Some n -> Some n
              | None ->
                  let us = utf8_decode p.value in
                  if
                    us <> [] && List.for_all is_id_continue_char us && is_id_start_char (List.hd us)
                    && not (Hashtbl.mem an.term_set (to_upper p.value))
                  then Some (to_upper p.value)
                  else None
            in
            (match name with Some n when Hashtbl.mem an.term_set n -> None | n -> n)
      else match find p with Some td -> Some td.name | None -> None
    in
    let term_name =
      match term_name with
      | Some n -> n
      | None -> let n = Printf.sprintf "__ANON_%d" an.anon_i in an.anon_i <- an.anon_i + 1; n
    in
    if not (Hashtbl.mem an.term_set term_name) then begin
      Hashtbl.replace an.term_set term_name ();
      let td = terminal_def term_name p in
      td.from_literal <- true;
      an.term_reverse <- (p, td) :: an.term_reverse;
      an.terminals <- an.terminals @ [ td ]
    end;
    term_name

  let prepare_anon (an : anon) (t : gtree) : gnode =
    match (t.data, t.children) with
    | "pattern", [ Pt p ] -> Sy (terminal ~filter_out:p.is_str (terminal_name an p))
    | "child_pattern", [ Pt p ] ->
        if not p.is_str then failwith "Larkita: child_pattern expects a string";
        Sy (terminal ~text:p.value (terminal_name an p))
    | _ -> T t

  (* ValidateSymbols *)
  let validate_symbols (t : gtree) : gnode = match (t.data, t.children) with "value", [ v ] -> v | _ -> T t

  (* ---------- EBNF to BNF ---------- *)

  let small_factor_threshold = 5
  let repeat_break_threshold = 50

  let rec small_factors (n : int) (max_factor : int) : (int * int) list =
    if n <= max_factor then [ (n, 0) ]
    else
      let rec try_a a =
        if a <= 1 then failwith "Failed to factorize"
        else
          let r = n / a and b = n mod a in
          if a + b <= max_factor then small_factors r max_factor @ [ (a, b) ] else try_a (a - 1)
      in
      try_a max_factor

  type ebnf = {
    mutable new_rules : (string * gtree) list;
    mutable rules_cache : ((gnode * string list * string) * gnode) list;
    mutable prefix : string;
    mutable i : int;
  }

  let terminal_kinds (n : gnode) : string list =
    match n with
    | Sy s when s.is_term -> [ symbol_fullrepr s ]
    | T t -> List.map (function Sy s -> symbol_fullrepr s | _ -> "") (scan_values (function Sy s -> s.is_term | _ -> false) t)
    | _ -> []

  let ebnf_transform (e : ebnf) (t : gtree) : gnode =
    let name_rule inner = let n = Printf.sprintf "__%s_%s_%d" e.prefix inner e.i in e.i <- e.i + 1; n in
    let cached key =
      List.find_map
        (fun ((k, kinds, tag), v) -> let k', kinds', tag' = key in if tag = tag' && kinds = kinds' && node_equal k k' then Some v else None)
        e.rules_cache
    in
    let add_rule key name tree =
      let t = Sy (nonterminal name) in
      e.new_rules <- e.new_rules @ [ (name, tree) ];
      e.rules_cache <- e.rules_cache @ [ (key, t) ];
      t
    in
    let add_recurse_rule type_ expr =
      let key = (expr, terminal_kinds expr, "recurse") in
      match cached key with
      | Some t -> t
      | None ->
          let name = name_rule type_ in
          let t = Sy (nonterminal name) in
          let tree = mk "expansions" [ mkt "expansion" [ expr ]; mkt "expansion" [ t; expr ] ] in
          add_rule key name tree
    in
    let add_repeat_rule a b target atom =
      let key = (mkt "repeat" [ target; atom ], terminal_kinds atom, Printf.sprintf "repeat %d %d" a b) in
      match cached key with
      | Some t -> t
      | None ->
          let name = name_rule (Printf.sprintf "repeat_a%d_b%d" a b) in
          let tree = mk "expansions" [ mkt "expansion" (List.init a (fun _ -> target) @ List.init b (fun _ -> atom)) ] in
          add_rule key name tree
    in
    let add_repeat_opt_rule a b target target_opt atom =
      let key = (mkt "repeat" [ target; atom ], terminal_kinds atom, Printf.sprintf "opt %d %d" a b) in
      match cached key with
      | Some t -> t
      | None ->
          let name = name_rule (Printf.sprintf "repeat_a%d_b%d_opt" a b) in
          let tree =
            mk "expansions"
              (List.init a (fun i -> mkt "expansion" (List.init i (fun _ -> target) @ [ target_opt ]))
              @ List.init b (fun i -> mkt "expansion" (List.init a (fun _ -> target) @ List.init i (fun _ -> atom))))
          in
          add_rule key name tree
    in
    let generate_repeats rule mn mx =
      if mx < repeat_break_threshold then
        mkt "expansions" (List.init (mx - mn + 1) (fun k -> mkt "expansion" (List.init (mn + k) (fun _ -> rule))))
      else begin
        let mn_target = List.fold_left (fun tg (a, b) -> add_repeat_rule a b tg rule) rule (small_factors mn small_factor_threshold) in
        if mx = mn then mn_target
        else begin
          let diff = mx - mn + 1 in
          let factors = small_factors diff small_factor_threshold in
          let diff_target = ref rule and diff_opt_target = ref (mkt "expansion" []) in
          List.iter
            (fun (a, b) ->
              diff_opt_target := add_repeat_opt_rule a b !diff_target !diff_opt_target rule;
              diff_target := add_repeat_rule a b !diff_target rule)
            (take (List.length factors - 1) factors);
          let a, b = List.nth factors (List.length factors - 1) in
          let diff_opt_target = add_repeat_opt_rule a b !diff_target !diff_opt_target rule in
          mkt "expansions" [ mkt "expansion" [ mn_target; diff_opt_target ] ]
        end
      end
    in
    match t.data with
    | "expr" -> (
        let rule = List.hd t.children in
        match tok_value (List.nth t.children 1) with
        | "?" -> mkt "expansions" [ rule; mkt "expansion" [] ]
        | "+" -> add_recurse_rule "plus" rule
        | "*" -> mkt "expansions" [ add_recurse_rule "star" rule; mkt "expansion" [] ]
        | "~" ->
            let mn, mx =
              match List.map (fun n -> int_of_string (tok_value n)) (drop 2 t.children) with
              | [ k ] -> (k, k)
              | [ mn; mx ] ->
                  if mx < mn || mn < 0 then
                    raise (Grammar_error (Printf.sprintf "Bad Range for %s (%d..%d isn't allowed)" "rule" mn mx));
                  (mn, mx)
              | _ -> assert false
            in
            generate_repeats rule mn mx
        | op -> failwith ("Larkita: unknown operator " ^ op))
    | "maybe" -> mkt "expansions" [ List.hd t.children; mkt "expansion" [] ]
    | _ -> T t

  (* ---------- Simplification (SimplifyRule_Visitor) ---------- *)

  let rec simplify (t : gtree) : unit = List.iter simplify_node (iter_subtrees t)

  and flatten (t : gtree) : unit = while expand_kids_by_data t [ t.data ] do () done

  and simplify_node (t : gtree) : unit =
    match t.data with
    | "expansion" ->
        flatten t;
        let rec find i = function
          | [] -> ()
          | T child :: _ when child.data = "expansions" ->
              let others = t.children in
              t.data <- "expansions";
              t.children <-
                List.map
                  (fun option ->
                    let nt = mk "expansion" (List.mapi (fun j other -> if j = i then option else other) others) in
                    simplify nt;
                    T nt)
                  (dedup ~eq:node_equal child.children);
              flatten t
          | _ :: rest -> find (i + 1) rest
        in
        find 0 t.children
    | "alias" -> (
        match t.children with
        | [ T rule; alias_name ] when rule.data = "expansions" ->
            t.data <- "expansions";
            t.children <- List.map (fun child -> mkt "alias" [ child; alias_name ]) rule.children
        | _ -> ())
    | "expansions" ->
        flatten t;
        let d = dedup ~eq:node_equal t.children in
        if List.length d <> List.length t.children then t.children <- d
    | _ -> ()

  (* RuleTreeToText: the alternatives of a rule as lists of symbols with their AstSpecs *)
  let rule_tree_to_text (t : gtree) : (symbol list * ast_spec option) list =
    let symbols (e : gtree) =
      List.map (function Sy s -> s | _ -> failwith "Larkita: unexpected node in a rule") e.children
    in
    let rec alternatives (n : gnode) =
      match n with
      | T { data = "expansions"; children; _ } -> List.concat_map alternatives children
      | T ({ data = "expansion"; _ } as e) -> [ (symbols e, None) ]
      | T { data = "alias"; children = [ T e; Sp spec ]; _ } -> [ (symbols e, Some spec) ]
      | Sy s -> [ ([ s ], None) ]
      | _ -> failwith "Larkita: unexpected node in a rule"
    in
    alternatives (T t)

  (* ---------- Grammars ---------- *)

  type definition = { d_is_term : bool; mutable d_tree : gtree option; d_options : int option (* priority *) }

  type grammar = {
    rule_defs : (string * gtree * int option) list;
    term_defs : (string * gtree option * int) list;
    ignore_names : string list;
    ast_ignore : string list;
    first_rule : string option;
  }

  let compile_grammar (g : grammar) (start : string list) : terminal_def list * rule list * string list =
    let term_defs = List.map (fun (n, t, p) -> (n, Option.map copy_tree t, p)) g.term_defs in
    let rule_defs = List.map (fun (n, t, o) -> (n, copy_tree t, o)) g.rule_defs in
    (* compile the terminals *)
    List.iter
      (fun (name, t, _) ->
        match t with
        | None -> ()
        | Some t -> (
            match find_data t "expansion" with
            | [ e ] when e.children = [] -> raise (Grammar_error (Printf.sprintf "Terminals cannot be empty (%s)" name))
            | _ -> ()))
      term_defs;
    let terminals =
      List.filter_map
        (fun (name, t, priority) ->
          match t with
          | None -> None
          | Some t -> (
              let prepared = transform_in_place prepare_literals t in
              match transform terminal_tree_to_pattern prepared with
              | Pt p -> Some (terminal_def ~priority name p)
              | _ -> failwith "Larkita: cannot compile terminal"))
        term_defs
    in
    (* 1. the shape of the abstract syntax tree of every alternative *)
    List.iter (fun (name, t, _) -> attach_ast_specs name t g.ast_ignore) rule_defs;
    (* 2. + 3. anonymous terminals and EBNF *)
    let an = make_anon terminals in
    let e = { new_rules = []; rules_cache = []; prefix = "anon"; i = 0 } in
    let rules =
      List.map
        (fun (name, t, options) ->
          e.prefix <- name;
          let t = tree_of (transform_in_place prepare_literals t) in
          let t = tree_of (transform_in_place validate_symbols t) in
          let t = tree_of (transform_in_place (prepare_anon an) t) in
          let res = transform_in_place (ebnf_transform e) t in
          (name, tree_of res, options))
        rule_defs
    in
    let rules = rules @ List.map (fun (name, t) -> (name, t, None)) e.new_rules in
    (* 4. compile the trees to rules *)
    let compiled =
      List.concat_map
        (fun (name, t, priority) ->
          simplify t;
          List.mapi
            (fun i (expansion, spec) -> { origin = name; expansion; order = i; priority; ast = spec })
            (rule_tree_to_text t))
        rules
    in
    (* duplicates *)
    let compiled =
      if List.length (dedup ~eq:rule_equal compiled) <> List.length compiled then begin
        List.iter
          (fun r ->
            let dups = List.filter (rule_equal r) compiled in
            if List.length dups > 1 && r.expansion <> [] then
              raise
                (Grammar_error
                   ("Rules defined twice: "
                   ^ String.concat "" (List.map (fun d -> "\n  * " ^ rule_to_string d) dups)
                   ^ "\n\n(Might happen due to colliding expansion of optionals: [] or ?)")))
          compiled;
        dedup ~eq:rule_equal compiled
      end
      else compiled
    in
    (* unused rules *)
    let rec filter_unused compiled =
      let used =
        List.concat_map
          (fun r -> List.filter_map (fun s -> if (not s.is_term) && s.name <> r.origin then Some s.name else None) r.expansion)
          compiled
        @ start
      in
      let kept = List.filter (fun r -> List.mem r.origin used) compiled in
      if List.length kept = List.length compiled then kept else filter_unused kept
    in
    let compiled = filter_unused compiled in
    (* unused terminals *)
    let used_terms = List.concat_map (fun r -> List.filter_map (fun s -> if s.is_term then Some s.name else None) r.expansion) compiled in
    let terminals = List.filter (fun (t : terminal_def) -> List.mem t.name used_terms || List.mem t.name g.ignore_names) an.terminals in
    (terminals, compiled, g.ignore_names)

  (* ---------- The grammar builder ---------- *)

  let grammars_dir = ref "grammars"   (* set by larkita.ml: the directory of common.lark *)

  type builder = {
    import_paths : string list;
    mutable definitions : (string * definition) list;
    mutable ignore_list : string list;
    mutable ast_ignore_list : string list;
    mutable first : string option;
  }

  let new_builder import_paths = { import_paths; definitions = []; ignore_list = []; ast_ignore_list = []; first = None }

  let grammar_error (is_term : bool) (msg : string) (names : string list) : 'a =
    let lower = if is_term then "terminal" else "rule" in
    let title = String.capitalize_ascii lower in
    let msg = ref msg in
    List.iteri
      (fun i name ->
        let postfix = if i = 0 then "" else string_of_int (i + 1) in
        msg := replace_all ("{name" ^ postfix ^ "}") name !msg;
        msg := replace_all ("{type" ^ postfix ^ "}") lower !msg;
        msg := replace_all ("{Type" ^ postfix ^ "}") title !msg)
      names;
    raise (Grammar_error !msg)

  let define ?(override = false) (b : builder) (name : string) (is_term : bool) (tree : gtree option) (options : int option) =
    if List.mem_assoc name b.definitions then begin
      if not override then grammar_error is_term "{Type} '{name}' defined more than once" [ name ]
    end
    else if override then grammar_error is_term "Cannot override a nonexisting {type} {name}" [ name ];
    if String.starts_with ~prefix:"__" name then
      grammar_error is_term "Names starting with double-underscore are reserved (Error at {name})" [ name ];
    let options = if is_term then Some (Option.value options ~default:1) else options in
    let d = { d_is_term = is_term; d_tree = tree; d_options = options } in
    if List.mem_assoc name b.definitions then
      b.definitions <- List.map (fun (n, d') -> if n = name then (n, d) else (n, d')) b.definitions
    else b.definitions <- b.definitions @ [ (name, d) ]

  let extend (b : builder) (name : string) (is_term : bool) (tree : gtree option) =
    match List.assoc_opt name b.definitions with
    | None -> grammar_error is_term "Can't extend {type} {name} as it wasn't defined before" [ name ]
    | Some d ->
        if is_term <> d.d_is_term then
          grammar_error is_term "Cannot extend {type} {name} - one is a terminal, while the other is not." [ name ];
        (match d.d_tree with
         | None -> grammar_error is_term "Can't extend {type} {name} - it is abstract." [ name ]
         | Some base -> base.children <- T (Option.get tree) :: base.children)

  let ignore_item (b : builder) (t : gtree) =
    let t = if t.data = "expansion" then mk "expansions" [ T t ] else t in
    let single_terminal =
      match t with
      | { data = "expansions"; children = [ T { data = "expansion"; children = [ T { data = "value"; children = [ Sy s ]; _ } ]; _ } ]; _ }
        when s.is_term -> Some s.name
      | _ -> None
    in
    match single_terminal with
    | Some name -> b.ignore_list <- b.ignore_list @ [ name ]
    | None ->
        let name = Printf.sprintf "__IGNORE_%d" (List.length b.ignore_list) in
        b.ignore_list <- b.ignore_list @ [ name ];
        b.definitions <- b.definitions @ [ (name, { d_is_term = true; d_tree = Some t; d_options = Some 0 }) ]

  (* the names of the symbols in the order of their first occurrence *)
  let find_used_symbols (t : gtree) : string list =
    dedup
      (List.concat_map
         (fun x ->
           if x.data = "expansion" then List.map (function Sy s -> s.name | _ -> "") (scan_values (function Sy _ -> true | _ -> false) x)
           else [])
         (iter_subtrees_topdown t))

  let resolve_term_references (term_dict : (string * gtree option) list) : unit =
    let changed = ref true in
    while !changed do
      changed := false;
      List.iter
        (fun (name, t) ->
          match t with
          | None -> ()
          | Some t ->
              List.iter
                (fun exp ->
                  match exp.children with
                  | [ Sy item ] when not item.is_term ->
                      raise
                        (Grammar_error
                           (Printf.sprintf "Rules aren't allowed inside terminals (%s in %s)" (Printf.sprintf "NonTerminal(%s)" (py_repr item.name)) name))
                  | [ Sy item ] -> (
                      match List.assoc_opt item.name term_dict with
                      | None | Some None -> raise (Grammar_error ("Terminal used but not defined: " ^ item.name))
                      | Some (Some value) -> exp.children <- [ T value ]; changed := true)
                  | _ -> ())
                (find_data t "value"))
        term_dict
    done;
    List.iter
      (fun (name, t) ->
        match t with
        | None -> ()
        | Some term ->
            List.iter
              (fun child ->
                match child with
                | T c ->
                    if List.exists (fun s -> s == term) (iter_subtrees c) then
                      raise
                        (Grammar_error
                           (Printf.sprintf "Recursion in terminal '%s' (recursion is only allowed in rules, not terminals)" name))
                | _ -> ())
              term.children)
      term_dict

  let parse_grammar (text : string) (name : string) : gtree =
    let tree =
      try meta_parse (text ^ "\n")
      with Unexpected_input e -> (
        let context = get_context e text in
        match e.kind with
        | Unexpected_characters _ ->
            raise
              (Grammar_error (Printf.sprintf "Unexpected input at line %d column %d in %s: \n\n%s" e.line e.column name context))
        | Unexpected_token { token; expected } -> (
            match translate_parser_exception e token expected with
            | Some error -> raise (Grammar_error (Printf.sprintf "%s, at line %d column %d\n\n%s" error e.line e.column context))
            | None -> raise (Unexpected_input e)))
    in
    (* PrepareGrammar *)
    tree_of
      (transform_in_place
         (fun t ->
           match (t.data, t.children) with
           | "terminal", [ Tk name ] -> Sy (terminal name.value)
           | "nonterminal", [ Tk name ] -> Sy (nonterminal name.value)
           | _ -> T t)
         (tree_of tree))

  let mangle_definition_tree (exp : gtree) (mangle : (string -> string) option) : gtree =
    match mangle with
    | None -> exp
    | Some m ->
        let exp = copy_tree exp in
        List.iter
          (fun t -> t.children <- List.map (function Sy s -> Sy { s with name = m s.name } | c -> c) t.children)
          (iter_subtrees exp);
        exp

  let unpack_definition (t : gtree) (mangle : (string -> string) option) : string * bool * gtree option * int option =
    let name, is_term, exp, opts =
      if t.data = "rule" then
        match t.children with
        | [ T modifiers; Tk name; T priority; T exp ] ->
            (match modifiers.children with
             | [ Tk m ] ->
                 raise
                   (Grammar_error
                      (Printf.sprintf "Rule modifiers like '%s' are not supported by Larkita (in rule %s)" m.value name.value))
             | _ -> ());
            let priority = match priority.children with [ Tk p ] -> Some (int_of_string p.value) | _ -> None in
            (name.value, false, exp, priority)
        | _ -> assert false
      else
        match t.children with
        | [ Tk name; T exp ] -> (name.value, true, exp, Some 0)
        | [ Tk name; Tk p; T exp ] -> (name.value, true, exp, Some (int_of_string p.value))
        | _ -> assert false
    in
    let name = match mangle with Some m -> m name | None -> name in
    (name, is_term, Some (mangle_definition_tree exp mangle), opts)

  let get_mangle (prefix : string) (aliases : (string * string) list) (base : (string -> string) option) : string -> string =
   fun s ->
    let s =
      match List.assoc_opt s aliases with
      | Some a -> a
      | None ->
          if String.starts_with ~prefix:"_" s then Printf.sprintf "_%s__%s" prefix (String.sub s 1 (String.length s - 1))
          else Printf.sprintf "%s__%s" prefix s
    in
    match base with Some m -> m s | None -> s

  let rec load (b : builder) (text : string) (grammar_name : string) (mangle : (string -> string) option) : unit =
    let tree = parse_grammar text grammar_name in
    (* the imports *)
    let imports = ref [] in
    List.iter
      (fun stmt ->
        match stmt with
        | T { data = "import"; children; _ } ->
            List.iter
              (fun item ->
                let item = tree_of item in
                let path_node, arg1 = match item.children with [ T p ] -> (p, None) | [ T p; a ] -> (p, Some a) | _ -> assert false in
                let names = List.map tok_value path_node.children in
                let dotted_path, aliases =
                  match arg1 with
                  | Some (T name_list) ->
                      let ns = List.map tok_value name_list.children in
                      (names, List.map (fun n -> (n, n)) ns)
                  | _ ->
                      let dotted = take (List.length names - 1) names in
                      if dotted = [] then raise (Grammar_error (Printf.sprintf "Nothing was imported from grammar `%s`" (List.hd names)));
                      let name = List.nth names (List.length names - 1) in
                      let alias = match arg1 with Some (Tk a) -> a.value | _ -> name in
                      (dotted, [ (name, alias) ])
                in
                let base_path =
                  if path_node.data = "import_lib" then None
                  else if grammar_name = "<string>" then Some (Sys.getcwd ())
                  else Some (Filename.dirname grammar_name)
                in
                match List.assoc_opt dotted_path !imports with
                | Some (_, al) -> al := List.fold_left (fun acc (k, v) -> (List.remove_assoc k acc) @ [ (k, v) ]) !al aliases
                | None -> imports := !imports @ [ (dotted_path, (base_path, ref aliases)) ])
              children
        | _ -> ())
      (tree_of (T tree)).children;
    List.iter (fun (dotted_path, (base_path, aliases)) -> do_import b dotted_path base_path !aliases mangle) !imports;
    (* the definitions *)
    List.iter
      (fun stmt ->
        let stmt = tree_of stmt in
        match stmt.data with
        | "term" | "rule" ->
            let name, is_term, exp, opts = unpack_definition stmt mangle in
            define b name is_term exp opts;
            if stmt.data = "rule" && mangle = None && b.first = None then b.first <- Some name
        | "override" ->
            let name, is_term, exp, opts = unpack_definition (tree_of (List.hd stmt.children)) mangle in
            define ~override:true b name is_term exp opts
        | "extend" ->
            let name, is_term, exp, _ = unpack_definition (tree_of (List.hd stmt.children)) mangle in
            extend b name is_term exp
        | "ignore" -> if mangle = None then List.iter (fun i -> ignore_item b (tree_of i)) stmt.children
        | "ast_ignore" ->
            if mangle = None then
              b.ast_ignore_list <- b.ast_ignore_list @ List.map (function Tk t -> literal_text t | _ -> assert false) stmt.children
        | "declare" ->
            List.iter
              (function
                | Sy s ->
                    if not s.is_term then
                      raise (Grammar_error (Printf.sprintf "Expecting terminal name to follow %%declare, but got rule name %s" (py_repr s.name)));
                    let name = match mangle with Some m -> m s.name | None -> s.name in
                    define b name true None None
                | _ -> assert false)
              stmt.children
        | "import" -> ()
        | d -> failwith ("Larkita: unexpected statement " ^ d))
      tree.children;
    resolve_term_references (List.filter_map (fun (n, d) -> if d.d_is_term then Some (n, d.d_tree) else None) b.definitions)

  and remove_unused (b : builder) (used : string list) : unit =
    let deps symbol =
      match List.assoc_opt symbol b.definitions with
      | Some { d_is_term = false; d_tree = Some t; _ } -> find_used_symbols t
      | _ -> []
    in
    (* breadth-first search *)
    let visited = Hashtbl.create 32 in
    let queue = Queue.create () in
    List.iter (fun u -> if not (Hashtbl.mem visited u) then (Hashtbl.add visited u (); Queue.add u queue)) used;
    while not (Queue.is_empty queue) do
      let node = Queue.pop queue in
      List.iter (fun n -> if not (Hashtbl.mem visited n) then (Hashtbl.add visited n (); Queue.add n queue)) (deps node)
    done;
    b.definitions <- List.filter (fun (k, _) -> Hashtbl.mem visited k) b.definitions

  and do_import (b : builder) (dotted_path : string list) (base_path : string option) (aliases : (string * string) list)
      (base_mangle : (string -> string) option) : unit =
    let mangle = get_mangle (String.concat "__" dotted_path) aliases base_mangle in
    let grammar_path = String.concat Filename.dir_sep dotted_path ^ ".lark" in
    let to_try =
      b.import_paths @ (match base_path with Some p -> [ p ] | None -> []) @ (if base_path = None then [ !grammars_dir ] else [])
    in
    let found =
      List.find_map
        (fun dir ->
          let joined = Filename.concat dir grammar_path in
          if Sys.file_exists joined then Some (joined, In_channel.with_open_bin joined In_channel.input_all) else None)
        to_try
    in
    match found with
    | None -> raise (Sys_error (Printf.sprintf "[Errno 2] No such file or directory: %s" (py_repr grammar_path)))
    | Some (joined, text) ->
        let gb = new_builder b.import_paths in
        load gb text joined (Some mangle);
        remove_unused gb (List.map (fun (k, _) -> mangle k) aliases);
        List.iter
          (fun (name, _) ->
            if List.mem_assoc name b.definitions then
              raise (Grammar_error (Printf.sprintf "Cannot import '%s' from '%s': Symbol already defined." name grammar_path)))
          gb.definitions;
        b.definitions <- b.definitions @ gb.definitions

  let validate (b : builder) : unit =
    List.iter
      (fun (name, d) ->
        match d.d_tree with
        | None -> ()
        | Some exp ->
            List.iter
              (fun sym ->
                if not (List.mem_assoc sym b.definitions) then
                  grammar_error d.d_is_term "{Type} '{name}' used but not defined (in {type2} {name2})" [ sym; name ])
              (find_used_symbols exp))
      b.definitions;
    let undefined = List.filter (fun n -> not (List.mem_assoc n b.definitions)) (dedup b.ignore_list) in
    if undefined <> [] then
      raise
        (Grammar_error
           (Printf.sprintf "Terminals {%s} were marked to ignore but were not defined!" (String.concat ", " (List.map py_repr undefined))))

  let build (b : builder) : grammar =
    validate b;
    {
      rule_defs = List.filter_map (fun (n, d) -> if d.d_is_term then None else Some (n, Option.get d.d_tree, d.d_options)) b.definitions;
      term_defs = List.filter_map (fun (n, d) -> if d.d_is_term then Some (n, d.d_tree, Option.value d.d_options ~default:0) else None) b.definitions;
      ignore_names = b.ignore_list;
      ast_ignore = b.ast_ignore_list;
      first_rule = b.first;
    }

  let load_grammar (text : string) (source : string) (import_paths : string list) : grammar =
    let b = new_builder import_paths in
    load b text source None;
    build b
end
